// Actual SDL event conversion and App resize, disconnected synthetic UI only.
#define main dialysis_device_main
#include "../src/ui/device_ui.cpp"
#undef main
#include <cassert>
int main(int argc,char** argv){
    assert(argc==2);App app(argv[1],false,"");
    for(auto size:{std::pair<int,int>{800,890},{1440,1000},{1100,890}}){
        SDL_SetWindowSize(app.window,size.first,size.second);
        SDL_Event event{};event.type=SDL_WINDOWEVENT;event.window.event=SDL_WINDOWEVENT_SIZE_CHANGED;event.window.data1=size.first;event.window.data2=size.second;
        assert(SDL_PushEvent(&event)==1);app.events();app.render();
        assert(app.width==size.first && app.height==size.second && app.framebuffer.size()==static_cast<size_t>(size.first*size.second));
        assert(lv_obj_get_width(app.guided->root)==size.first);
    }
    lv_area_t bounds;lv_obj_get_coords(app.guided->widgets.at("MOTION"),&bounds);
    auto finger=[&](uint32_t type,SDL_FingerID id){SDL_Event e{};e.type=type;e.tfinger.fingerId=id;e.tfinger.x=((bounds.x1+bounds.x2)/2.0f)/app.width;e.tfinger.y=((bounds.y1+bounds.y2)/2.0f)/app.height;assert(SDL_PushEvent(&e)==1);app.events();lv_indev_read(app.input_device);};
    for(auto tab:{std::pair<const char*,int>{"BLOOD_TAB",1},{"FLUID_TAB",2},{"HOME",0}}){
        lv_obj_get_coords(app.guided->widgets.at(tab.first),&bounds);
        finger(SDL_FINGERDOWN,10);finger(SDL_FINGERUP,10);
        assert(app.guided->page==tab.second);
    }
    lv_obj_get_coords(app.guided->widgets.at("MOTION"),&bounds);
    finger(SDL_FINGERDOWN,10);finger(SDL_FINGERDOWN,20);assert(app.touch && *app.touch==10);
    finger(SDL_FINGERUP,20);assert(app.touch && *app.touch==10);
    finger(SDL_FINGERUP,10);assert(!app.touch && app.guided->overview->state.reduced);
    // Synthetic mouse generated by SDL for touch must not double-activate.
    for(auto type:{SDL_MOUSEBUTTONDOWN,SDL_MOUSEBUTTONUP}){SDL_Event e{};e.type=type;e.button.which=SDL_TOUCH_MOUSEID;e.button.button=SDL_BUTTON_LEFT;e.button.x=(bounds.x1+bounds.x2)/2;e.button.y=(bounds.y1+bounds.y2)/2;assert(SDL_PushEvent(&e)==1);app.events();lv_indev_read(app.input_device);}
    assert(app.guided->overview->state.reduced);
    finger(SDL_FINGERDOWN,10);SDL_Event lost{};lost.type=SDL_WINDOWEVENT;lost.window.event=SDL_WINDOWEVENT_FOCUS_LOST;assert(SDL_PushEvent(&lost)==1);app.events();lv_indev_read(app.input_device);
    assert(!app.touch && !app.mouse_pressed && app.guided->overview->state.reduced); // cancel, not click
    // Confirmation buttons use the same icon helper before first layout.
    auto* parent=lv_obj_create(lv_screen_active());lv_obj_set_size(parent,500,200);
    auto* confirm=app.button("CONFIRM","Confirm",10,10,220,parent);lv_obj_update_layout(parent);
    assert(lv_obj_get_height(confirm)>=48 && lv_obj_get_width(lv_obj_get_child(confirm,0))>40);
    std::cout<<"SDL resize, finger ownership, duplicate mouse suppression, focus cancellation and labels passed\n";
}
